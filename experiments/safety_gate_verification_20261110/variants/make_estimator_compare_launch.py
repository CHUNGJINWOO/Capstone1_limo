#!/usr/bin/env python3
"""Generate the EXPERIMENT launch variants/sim_diff_estimator_compare.launch.py from the current repo Differential sim launch
(the repo launch is never edited). It adds the estimators the sim launch lacks, copied from the REAL launch definitions:
b0 (wheel /odom), f1b (EKF: wheel vx,vy + IMU yaw,wz), f3b (complementary filter + slip gate), and keeps f4 / f5_improved.
F4 always runs (it already does in the sim launch; the safety gate requires /odometry/lidar_odom in every mode)."""
import os
root = os.path.expanduser('~/school/2026-2/Capstone1_limo/capstone_ws/src/limo_capstone/launch/')
s = open(root + 'limo_integrated_auto_mapping_sim_diff.launch.py').read()
def rep(old, new):
    global s
    assert s.count(old) == 1, old
    s = s.replace(old, new)
rep("choices=['f4', 'f5_improved'],", "choices=['b0', 'f1b', 'f3b', 'f4', 'f5_improved'],")
rep("    config_ekf = os.path.join(pkg_limo_capstone, 'config', 'fusion_f5_improved.yaml')\n",
    "    config_ekf = os.path.join(pkg_limo_capstone, 'config', 'fusion_f5_improved.yaml')\n"
    "    config_ekf_f1b = os.path.join(pkg_limo_capstone, 'config', 'ekf_tuned.yaml')\n")
extra = '''    # ---- estimator-comparison additions (copied from limo_integrated_auto_mapping_real.launch.py) ----
    is_b0 = PythonExpression(["'", estimator_type, "' == 'b0'"])
    is_f1b = PythonExpression(["'", estimator_type, "' == 'f1b'"])
    is_f3b = PythonExpression(["'", estimator_type, "' == 'f3b'"])
    f1b_ekf_node = Node(package='robot_localization', executable='ekf_node', name='ekf_f1b_node', output='screen',
                        parameters=[config_ekf_f1b, {'use_sim_time': use_sim_time}],
                        remappings=[('odometry/filtered', '/odometry/ekf_tuned')], condition=IfCondition(is_f1b))
    comp_filter_node = Node(package='limo_capstone', executable='complementary_filter_node', name='complementary_filter_node',
                            output='screen', parameters=[{'use_sim_time': use_sim_time}], condition=IfCondition(is_f3b))
    def _relay(topic, cond):
        return Node(package='limo_capstone', executable='odom_tf_relay_node', name='odom_tf_relay_node', output='screen',
                    parameters=[{'active_odom_topic': topic, 'nav2_odom_topic': '/odom_nav2', 'odom_frame': 'odom',
                                 'base_frame': 'base_footprint', 'use_sim_time': use_sim_time}], condition=IfCondition(cond))
    relay_b0 = _relay('/odom', is_b0)
    relay_f1b = _relay('/odometry/ekf_tuned', is_f1b)
    relay_f3b = _relay('/odometry/comp_slip_gate', is_f3b)

'''
rep("    # 6. SLAM Toolbox", extra + "    # 6. SLAM Toolbox")
rep("        relay_f5,\n", "        relay_f5,\n        f1b_ekf_node,\n        comp_filter_node,\n        relay_b0,\n        relay_f1b,\n        relay_f3b,\n")
hdr = '"""EXPERIMENT launch generated by make_estimator_compare_launch.py - do not edit; the repo launch is unchanged."""\n'
open(os.path.dirname(os.path.abspath(__file__)) + '/sim_diff_estimator_compare.launch.py', 'w').write(hdr + s)
print('written')
