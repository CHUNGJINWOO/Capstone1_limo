#!/usr/bin/env python3
"""Generate two EXPERIMENT launch files from the current repo Differential sim launch (the repo launch is never edited):
  sim_diff_relaxed_passive.launch.py : original explore_lite drives (start_explore:=true) + two explore_relaxed nodes in dry_run
                                       (cap 0 control and cap CAP with reachability) that only publish candidates.
  sim_diff_relaxed_drive.launch.py   : explore_relaxed is the explorer (args: bfs_cap, check_reach); original explore is not started.
"""
import os, sys
src = os.path.expanduser('~/school/2026-2/Capstone1_limo/capstone_ws/src/limo_capstone/launch/limo_integrated_auto_mapping_sim_diff.launch.py')
s = open(src).read()
old = """    explore_node = Node(
        package='explore_lite',
        executable='explore',
        name='explore_node',
        output='screen',
        parameters=[config_explore, {'use_sim_time': use_sim_time}],
        condition=IfCondition(start_explore)
    )
"""
assert s.count(old) == 1
common = """    # ---- explore_relaxed experiment (values copied from config/integrated_explore_params.yaml) ----
    base_explore_params = {
        'robot_base_frame': 'base_footprint', 'costmap_topic': '/global_costmap/costmap',
        'costmap_updates_topic': '/global_costmap/costmap_updates', 'visualize': True, 'planner_frequency': 0.5,
        'progress_timeout': 30.0, 'potential_scale': 3.0, 'orientation_scale': 0.0, 'gain_scale': 1.0,
        'transform_tolerance': 0.6, 'min_frontier_size': 0.35, 'use_sim_time': True,
    }

    def relaxed_node(name, cap, check_reach, dry_run, ns_topics, condition=None, mode='nav2'):
        p = dict(base_explore_params)
        p.update({'bfs_max_traverse_cost': cap, 'check_reachability': check_reach, 'dry_run': dry_run, 'reachability_mode': mode})
        remaps = []
        if ns_topics:
            remaps = [('explore_relaxed/candidates', f'/relaxed/{name}/candidates'), ('explore_relaxed/status', f'/relaxed/{name}/status'),
                      ('explore_relaxed/resume', f'/relaxed/{name}/resume'), ('explore_relaxed/frontiers', f'/relaxed/{name}/frontiers')]
        return Node(package='explore_relaxed', executable='explore_relaxed', name=name, output='screen',
                    parameters=[p], remappings=remaps, condition=condition)
"""
passive = common + """    explore_node = Node(
        package='explore_lite', executable='explore', name='explore_node', output='screen',
        parameters=[config_explore, {'use_sim_time': use_sim_time}], condition=IfCondition(start_explore)
    )
    relaxed_cap0 = relaxed_node('relaxed_cap0', 0, False, True, True)
    relaxed_cap60 = relaxed_node('relaxed_cap60', 60, True, True, True)
"""
drive = common + """    explore_node = relaxed_node('explore_relaxed_node', int(os.environ.get('RELAXED_CAP', '0')),
                                os.environ.get('RELAXED_CHECK', '0') == '1', False, False,
                                condition=IfCondition(start_explore), mode=os.environ.get('RELAXED_MODE', 'nav2'))
"""
hdr = '# EXPERIMENT variant generated by make_explore_variant_launches.py; the repo launch is untouched.\n'
p = s.replace(old, passive).replace("        explore_node,\n", "        explore_node,\n        relaxed_cap0,\n        relaxed_cap60,\n")
assert p.count("relaxed_cap60,\n") == 1
d = s.replace(old, drive)
here = os.path.dirname(os.path.abspath(__file__))
open(f'{here}/sim_diff_relaxed_passive.launch.py', 'w').write(hdr + p)
open(f'{here}/sim_diff_relaxed_drive.launch.py', 'w').write(hdr + d)
print('written')
